export const FORCE_UPDATE = false

// رابط التحميل (للتحديثات اليدوية)
export const DOWNLOAD_URL = ''

// معلومات الإصدار الكاملة
export interface VersionInfo {
  version: string
  releaseDate: string
  changelog: typeof CHANGELOG
  forceUpdate: boolean
  downloadUrl: string
}

